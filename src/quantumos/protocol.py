"""Local IPC protocol version 1 (QOS-IF 3章・4章).

Framing: a 4-byte unsigned big-endian length followed by that many bytes of
UTF-8 JSON.  Request and response bodies are 1 B … 8 MiB.  The server handles
exactly one frame per connection, replies, and closes.
"""

from __future__ import annotations

import socket
import struct
import time
from dataclasses import dataclass

from . import errors, strictjson
from .circuit import Circuit, validate_circuit
from .errors import QosError
from .limits import (
    BACKEND_MAX_QUBITS,
    FRAME_MAX_BYTES,
    FRAME_MIN_BYTES,
    MAX_CIRCUIT_BYTES,
    SHOTS_DEFAULT,
    SHOTS_MAX,
    SHOTS_MIN,
)
from .seed import parse_seed

PROTOCOL_VERSION = 1
DEFAULT_SOCKET_PATH = "/run/quantumos/quantum.sock"

OPS = ("validate", "run", "status")
_ALLOWED_KEYS = {
    "validate": {"protocol_version", "op", "circuit"},
    "run": {"protocol_version", "op", "circuit", "shots", "seed"},
    "status": {"protocol_version", "op"},
}

_LEN = struct.Struct(">I")


class FrameError(Exception):
    """Framing violation: the connection is closed without a response."""


# --------------------------------------------------------------------------
# Framing
# --------------------------------------------------------------------------
def encode_frame(body: bytes) -> bytes:
    if not (FRAME_MIN_BYTES <= len(body) <= FRAME_MAX_BYTES):
        raise FrameError(f"frame body length {len(body)} out of range")
    return _LEN.pack(len(body)) + body


def _recv_exact(sock: socket.socket, n: int, deadline: float | None) -> bytes:
    buf = bytearray()
    while len(buf) < n:
        if deadline is not None:
            remaining = deadline - time.monotonic()
            if remaining <= 0:
                raise FrameError("read deadline exceeded")
            sock.settimeout(remaining)
        try:
            chunk = sock.recv(min(n - len(buf), 1 << 20))
        except socket.timeout as exc:
            raise FrameError("read deadline exceeded") from exc
        if not chunk:
            raise FrameError("connection closed mid-frame")
        buf += chunk
    return bytes(buf)


def read_frame(sock: socket.socket, timeout: float | None = None) -> bytes:
    """Read one frame.  Raises ``FrameError`` on any framing violation."""
    deadline = None if timeout is None else time.monotonic() + timeout
    header = _recv_exact(sock, 4, deadline)
    (length,) = _LEN.unpack(header)
    if not (FRAME_MIN_BYTES <= length <= FRAME_MAX_BYTES):
        raise FrameError(f"frame length {length} out of range")
    return _recv_exact(sock, length, deadline)


def write_frame(sock: socket.socket, body: bytes) -> None:
    sock.sendall(encode_frame(body))


# --------------------------------------------------------------------------
# Requests
# --------------------------------------------------------------------------
@dataclass(frozen=True)
class Request:
    op: str
    circuit: Circuit | None = None
    shots: int = SHOTS_DEFAULT
    seed: int | None = None  # None → generated by the service


def _is_int(v: object) -> bool:
    return isinstance(v, int) and not isinstance(v, bool)


def parse_request_envelope(body: bytes) -> tuple[dict, dict[str, int]]:
    """Decode the request and check version, op and key set.

    Returns the raw object and the UTF-8 sizes of top-level values.
    """
    try:
        obj, sizes = strictjson.loads_object_with_spans(body)
    except strictjson.StrictJSONError as exc:
        raise QosError(errors.PROTOCOL_INVALID, f"malformed request: {exc}") from exc
    if not isinstance(obj, dict):
        raise QosError(errors.PROTOCOL_INVALID, "request must be a JSON object")
    if "protocol_version" not in obj:
        raise QosError(errors.PROTOCOL_INVALID, "missing key: protocol_version")
    pv = obj["protocol_version"]
    if not _is_int(pv):
        raise QosError(errors.PROTOCOL_INVALID, "protocol_version must be an integer")
    if pv != PROTOCOL_VERSION:
        raise QosError(errors.PROTOCOL_UNSUPPORTED, f"unsupported protocol_version: {pv}")
    op = obj.get("op")
    if not isinstance(op, str) or op not in OPS:
        raise QosError(errors.PROTOCOL_INVALID, "op must be one of validate, run, status")
    for key in obj:
        if key not in _ALLOWED_KEYS[op]:
            raise QosError(errors.PROTOCOL_INVALID, f"unknown key for {op}: {key}")
    if op in ("validate", "run") and "circuit" not in obj:
        raise QosError(errors.PROTOCOL_INVALID, "missing key: circuit")
    return obj, sizes


def parse_request(body: bytes) -> Request:
    """Full validation in the order of QOS-FD OS-04 (minus authorisation,
    slot availability and seed generation, which are the service's job):
    message → circuit → shots → seed → execution limit."""
    obj, sizes = parse_request_envelope(body)
    op = obj["op"]
    if op == "status":
        return Request(op="status")

    if sizes.get("circuit", 0) > MAX_CIRCUIT_BYTES:
        raise QosError(errors.CIRCUIT_INVALID, "circuit exceeds 4 MiB")
    circuit = validate_circuit(obj["circuit"])
    if op == "validate":
        return Request(op="validate", circuit=circuit)

    shots = SHOTS_DEFAULT
    if "shots" in obj:
        shots = obj["shots"]
        if not _is_int(shots) or not (SHOTS_MIN <= shots <= SHOTS_MAX):
            raise QosError(
                errors.RUN_OPTION_INVALID,
                f"shots must be an integer in {SHOTS_MIN}..{SHOTS_MAX}",
            )
    seed = None
    if "seed" in obj:
        try:
            seed = parse_seed(obj["seed"])
        except ValueError as exc:
            raise QosError(errors.RUN_OPTION_INVALID, f"Invalid seed: {exc}") from exc
    if circuit.n_qubits > BACKEND_MAX_QUBITS:
        raise QosError(
            errors.BACKEND_LIMIT,
            f"n_qubits {circuit.n_qubits} exceeds backend limit {BACKEND_MAX_QUBITS}",
        )
    return Request(op="run", circuit=circuit, shots=shots, seed=seed)


# --------------------------------------------------------------------------
# Responses
# --------------------------------------------------------------------------
def ok_response(result: dict) -> bytes:
    return strictjson.dumps(
        {"protocol_version": PROTOCOL_VERSION, "ok": True, "result": result}
    ).encode("utf-8")


def error_response(code: str, message: str) -> bytes:
    return strictjson.dumps(
        {
            "protocol_version": PROTOCOL_VERSION,
            "ok": False,
            "error": {"code": code, "message": message},
        }
    ).encode("utf-8")


def parse_response(body: bytes) -> dict:
    """Validate a response envelope (client side).  Returns the decoded object.

    Raises ``QosError(TRANSPORT_ERROR)`` if the response is malformed.
    """
    def bad(msg: str) -> QosError:
        return QosError(errors.TRANSPORT_ERROR, f"invalid response: {msg}")

    try:
        obj = strictjson.loads(body)
    except strictjson.StrictJSONError as exc:
        raise bad(str(exc)) from exc
    if not isinstance(obj, dict):
        raise bad("not an object")
    if obj.get("protocol_version") != PROTOCOL_VERSION or not _is_int(
        obj.get("protocol_version")
    ):
        raise bad("protocol_version")
    ok = obj.get("ok")
    if not isinstance(ok, bool):
        raise bad("ok")
    if ok:
        if set(obj) != {"protocol_version", "ok", "result"} or not isinstance(
            obj["result"], dict
        ):
            raise bad("result")
    else:
        err = obj.get("error")
        if (
            set(obj) != {"protocol_version", "ok", "error"}
            or not isinstance(err, dict)
            or not isinstance(err.get("code"), str)
            or not isinstance(err.get("message"), str)
        ):
            raise bad("error")
    return obj
